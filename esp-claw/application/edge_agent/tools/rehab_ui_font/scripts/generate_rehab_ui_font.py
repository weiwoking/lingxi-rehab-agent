def write_utf8_sig_crlf(path: Path, text: str) -> None:
    normalized = text.replace("\r\n", "\n").replace("\n", "\r\n")
    path.write_bytes(b"\xef\xbb\xbf" + normalized.encode("utf-8"))


def compact_ranges(codepoints: list[int]) -> list[str]:
    ranges: list[tuple[int, int]] = []
    start = previous = codepoints[0]
    for codepoint in codepoints[1:]:
        if codepoint == previous + 1:
            previous = codepoint
            continue
        ranges.append((start, previous))
        start = previous = codepoint
    ranges.append((start, previous))
    return [
        f"0x{start:X}" if start == end else f"0x{start:X}-0x{end:X}"
        for start, end in ranges
    ]


def converter_version(converter: Path) -> str:
    package = converter.parent / "package.json"
    if package.is_file():
        return str(
            json.loads(package.read_text(encoding="utf-8"))["version"]
        )
    return "unknown"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def render_runtime_text_helper(glyphs: str, glyph_count: int) -> str:
    return f"""-- Generated by tools/rehab_ui_font/scripts/generate_rehab_ui_font.py.
-- Unsupported dynamic characters are replaced visibly instead of rendering
-- as blank tofu boxes. Do not edit this file by hand.
local M = {{}}
local SUPPORTED = [==[{glyphs}]==]

local function utf8_length(first)
  if first < 0x80 then return 1 end
  if first >= 0xC2 and first <= 0xDF then return 2 end
  if first >= 0xE0 and first <= 0xEF then return 3 end
  if first >= 0xF0 and first <= 0xF4 then return 4 end
  return nil
end

local function valid_sequence(text, index, count)
  if index + count - 1 > #text then return false end
  for offset = 1, count - 1 do
    local byte = string.byte(text, index + offset)
    if not byte or byte < 0x80 or byte > 0xBF then return false end
  end
  return true
end

function M.sanitize(value, max_bytes)
  local text = tostring(value or "")
  local output = {{}}
  local output_bytes = 0
  local index = 1
  while index <= #text do
    local first = string.byte(text, index)
    local count = first and utf8_length(first) or nil
    local character
    if count and valid_sequence(text, index, count) then
      character = string.sub(text, index, index + count - 1)
      index = index + count
    else
      character = nil
      index = index + 1
    end
    local replacement = character
    if character == "\\n" or character == "\\r" or character == "\\t" then
      replacement = character
    elseif not character or
        not string.find(SUPPORTED, character, 1, true) then
      replacement = "？"
    end
    if max_bytes and output_bytes + #replacement > max_bytes then
      break
    end
    output[#output + 1] = replacement
    output_bytes = output_bytes + #replacement
  end
  return table.concat(output)
end

M.supported_glyph_count = {glyph_count}
return M
"""


def load_source_reference() -> tuple[dict[str, object], Path]:
    reference = json.loads(SOURCE_REFERENCE.read_text(encoding="utf-8"))
    expected = reference.get("relative_or_absolute_expected_path")
    expected_hash = reference.get("sha256")
    if not isinstance(expected, str) or not expected:
        raise SystemExit("source reference has no expected font path")
    if not isinstance(expected_hash, str) or not expected_hash:
        raise SystemExit("source reference has no SHA256")
    source = Path(expected)
    if not source.is_absolute():
        source = REPOSITORY / source
    source = source.resolve()
    if not source.is_file():
        raise SystemExit(f"font source from reference not found: {source}")
    actual_hash = sha256(source)
    if actual_hash.lower() != expected_hash.lower():
        raise SystemExit(
            "font source SHA256 mismatch: "
            f"expected {expected_hash.lower()}, got {actual_hash}"
        )
    return reference, source


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--converter",
        type=Path,
        required=True,
        help="Path to the installed lv_font_conv.js",
    )
    parser.add_argument(
        "--font-source",
        type=Path,
        help="Source Han Sans SC OTF; defaults to the LVGL managed component",
    )
    args = parser.parse_args()

    _, referenced_font_source = load_source_reference()
    font_source = args.font_source or referenced_font_source
    converter = args.converter.resolve()
    font_source = font_source.resolve()
    if not converter.is_file():
        raise SystemExit(f"converter not found: {converter}")
    if not font_source.is_file():
        raise SystemExit(f"font source not found: {font_source}")
    if sha256(font_source) != sha256(referenced_font_source):
        raise SystemExit(
            "--font-source does not match the source_font_reference SHA256"
        )

    glyph_path = GLYPHS / "rehab_ui_glyphs.txt"
    baseline = glyph_path.read_text(encoding="utf-8-sig").strip("\r\n")
    baseline_codepoints = {ord(character) for character in baseline}
    production_values, production_records = production_codepoints()
    gb2312_values = gb2312_level1_codepoints()
    reasoning_sample_values = reasoning_sample_supplement_codepoints()
    fixed_values = {
        ord(character)
        for text in REQUIRED_FIXED_TEXTS
        for character in text
    }
    codepoints = sorted(
        baseline_codepoints
        | set(range(0x20, 0x7F))
        | gb2312_values
        | {ord(character) for character in COMMON_PUNCTUATION}
        | production_values
        | fixed_values
        | reasoning_sample_values
    )
    missing_required = REQUIRED_CODEPOINTS - set(codepoints)
    if missing_required:
        formatted = ", ".join(f"U+{value:04X}" for value in missing_required)
        raise SystemExit(f"required UI codepoints missing from source: {formatted}")

    glyphs = "".join(chr(codepoint) for codepoint in codepoints)
    range_items = compact_ranges(codepoints)
    range_text = ",".join(range_items)
    codepoint_lines = [
        f"U+{codepoint:04X} "
        f"{'SPACE' if codepoint == 0x20 else chr(codepoint)}"
        for codepoint in codepoints
    ]

    manifest_path = GLYPHS / "rehab_ui_glyph_manifest.json"
    manifest = json.loads(
        manifest_path.read_text(encoding="utf-8-sig")
    )
    # The production scan and REQUIRED_FIXED_TEXTS are authoritative. Do not
    # carry stale task labels forward from an older generated manifest.
    prior_required_texts: list[str] = []
    manifest.update(
        {
            "generated_for": (
                "Stage 8C-1D Rehab UI production text plus GB2312 Level-1"
            ),
            "font_source_family": "Source Han Sans SC",
            "font_source_format": "OTF",
            "font_pixel_size": 20,
            "font_bpp": 1,
            "glyph_count": len(codepoints),
            "missing_glyph_count": 0,
            "gb2312_level1_count": len(gb2312_values),
            "gb2312_level1_source": (
                "Python gb2312 decode of B0A1-D6FE and D7A1-D7F9"
            ),
            "reasoning_sample_supplement_source": (
                "source/reasoning_sample_supplement.txt"
            ),
            "reasoning_sample_supplement_count": len(
                reasoning_sample_values
            ),
            "reasoning_sample_supplement_codepoints": [
                f"U+{value:04X}"
                for value in sorted(reasoning_sample_values)
            ],
            "common_punctuation": COMMON_PUNCTUATION,
            "ranges": range_items,
            "required_texts": list(
                dict.fromkeys([*prior_required_texts, *REQUIRED_TEXTS])
            ),
            "source_files_scanned_count": len(production_records),
            "source_files_scanned": production_records,
            "coverage_before_generation": {
                "glyph_count": len(baseline_codepoints),
                "missing_production_codepoints": [
                    f"U+{value:04X}"
                    for value in sorted(production_values - baseline_codepoints)
                ],
                "missing_fixed_text_codepoints": [
                    f"U+{value:04X}"
                    for value in sorted(fixed_values - baseline_codepoints)
                ],
                "missing_reasoning_sample_codepoints": [
                    f"U+{value:04X}"
                    for value in sorted(
                        reasoning_sample_values - baseline_codepoints
                    )
                ],
            },
            "generator": {
                "tool": "lv_font_conv",
                "version": converter_version(converter),
                "size": 20,
                "bpp": 1,
                "format": "bin",
                "compression": "none",
                "range_source": "glyphs/rehab_ui_codepoint_ranges.txt",
            },
            "note": (
                "Source font is a local build input; only the generated "
                "subset binfont is included in SYSTEM."
            ),
        }
    )

    CANONICAL_FONT.parent.mkdir(parents=True, exist_ok=True)
    DEPLOYMENT_FONT.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix="rehab_ui_font_", dir=WORKSPACE
    ) as temporary:
        generated_bin = Path(temporary) / "rehab_cn_20.bin"
        command = [
            "node",
            str(converter),
            "--font",
            str(font_source),
            "--size",
            "20",
            "--bpp",
            "1",
            "--format",
            "bin",
            "--range",
            range_text,
            "--no-compress",
            "--output",
            str(generated_bin),
        ]
        subprocess.run(command, check=True)
        parsed = parse(generated_bin, codepoints)
        missing_binary = [
            label
            for label, descriptor in parsed["glyphs"].items()
            if descriptor is None
        ]
        if missing_binary:
            raise SystemExit(
                "generated binary is missing: " + ", ".join(missing_binary)
            )
        validated_temporary = CANONICAL_FONT.with_suffix(
            ".bin.validated.tmp"
        )
        shutil.copyfile(generated_bin, validated_temporary)

    write_utf8_sig_crlf(glyph_path, glyphs + "\n")
    write_utf8_sig_crlf(
        GLYPHS / "rehab_ui_codepoints.txt",
        "\n".join(codepoint_lines) + "\n",
    )
    write_utf8_sig_crlf(
        GLYPHS / "rehab_ui_codepoint_ranges.txt",
        range_text + "\n",
    )
    write_utf8_sig_crlf(
        manifest_path,
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
    )

    # Only publish after conversion, parsing, required-glyph checks, and all
    # metadata writes have succeeded. Deployment uses a same-directory
    # temporary so os.replace remains atomic on Windows and POSIX.
    os.replace(validated_temporary, CANONICAL_FONT)
    deployment_temporary = DEPLOYMENT_FONT.with_suffix(".bin.tmp")
    shutil.copyfile(CANONICAL_FONT, deployment_temporary)
    if sha256(CANONICAL_FONT) != sha256(deployment_temporary):
        deployment_temporary.unlink(missing_ok=True)
        raise SystemExit("canonical/deployment temporary copy SHA256 mismatch")
    os.replace(deployment_temporary, DEPLOYMENT_FONT)
    runtime_text_temporary = RUNTIME_TEXT_HELPER.with_suffix(".lua.tmp")
    runtime_text = render_runtime_text_helper(glyphs, len(codepoints))
    normalized_runtime_text = (
        runtime_text.replace("\r\n", "\n").replace("\n", "\r\n")
    )
    runtime_text_temporary.write_bytes(normalized_runtime_text.encode("utf-8"))
    os.replace(runtime_text_temporary, RUNTIME_TEXT_HELPER)
    theme = RUNTIME_THEME.read_text(encoding="utf-8-sig")
    updated_theme, replacements = re.subn(
        r"(font_glyph_count\s*=\s*)\d+",
        rf"\g<1>{len(codepoints)}",
        theme,
        count=1,
    )
    if replacements != 1:
        raise SystemExit("runtime theme font_glyph_count was not found")
    theme_temporary = RUNTIME_THEME.with_suffix(".lua.tmp")
    theme_temporary.write_text(updated_theme, encoding="utf-8")
    os.replace(theme_temporary, RUNTIME_THEME)

    added = sorted(set(codepoints) - baseline_codepoints)
    print(f"glyph_count={len(codepoints)}")
    print(
        "added_codepoints="
        + ",".join(f"U+{codepoint:04X}" for codepoint in added)
    )
    print(f"binary_size={parsed['file_size']}")
    print(f"binary_sha256={parsed['sha256']}")


if __name__ == "__main__":
    main()
